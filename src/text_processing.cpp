        std::string joinWords(const std::vector<std::string>& words)
        {
            std::ostringstream stream;
            for (size_t i = 0; i < words.size(); ++i)
            {
                if (i != 0)
                {
                    stream << ' ';
                }
                stream << words[i];
            }
            return stream.str();
        }

        std::string numberToWords(int64_t number)
        {
            if (number < 0)
            {
                return "minus " + numberToWords(-number);
            }
            if (number < 20)
            {
                return smallNumbers()[static_cast<size_t>(number)];
            }
            if (number < 100)
            {
                const auto tens = number / 10;
                const auto remainder = number % 10;
                if (remainder == 0)
                {
                    return tensNumbers()[static_cast<size_t>(tens)];
                }
                return tensNumbers()[static_cast<size_t>(tens)] + " " + smallNumbers()[static_cast<size_t>(remainder)];
            }
            if (number < 1000)
            {
                const auto hundreds = number / 100;
                const auto remainder = number % 100;
                if (remainder == 0)
                {
                    return smallNumbers()[static_cast<size_t>(hundreds)] + " hundred";
                }
                return smallNumbers()[static_cast<size_t>(hundreds)] + " hundred " + numberToWords(remainder);
            }

            const std::vector<std::pair<int64_t, std::string>> scales = {
                {1000000000LL, "billion"},
                {1000000LL, "million"},
                {1000LL, "thousand"}};
            for (const auto& scale : scales)
            {
                if (number >= scale.first)
                {
                    const auto major = number / scale.first;
                    const auto remainder = number % scale.first;
                    auto result = numberToWords(major) + " " + scale.second;
                    if (remainder != 0)
                    {
                        result += " " + numberToWords(remainder);
                    }
                    return result;
                }
            }

            return "";
        }

        std::string ordinalToWords(int64_t number)
        {
            static const std::unordered_map<int64_t, std::string> irregular = {
                {0, "zeroth"},
                {1, "first"},
                {2, "second"},
                {3, "third"},
                {4, "fourth"},
                {5, "fifth"},
                {6, "sixth"},
                {7, "seventh"},
                {8, "eighth"},
                {9, "ninth"},
                {10, "tenth"},
                {11, "eleventh"},
                {12, "twelfth"},
                {13, "thirteenth"},
                {14, "fourteenth"},
                {15, "fifteenth"},
                {16, "sixteenth"},
                {17, "seventeenth"},
                {18, "eighteenth"},
                {19, "nineteenth"}};

            const auto found = irregular.find(number);
            if (found != irregular.end())
            {
                return found->second;
            }
            if (number < 100 && number % 10 == 0)
            {
                auto base = tensNumbers()[static_cast<size_t>(number / 10)];
                if (base.size() >= 1 && base.back() == 'y')
                {
                    base.pop_back();
                    base += "ieth";
                }
                return base;
            }

            const auto base = numberToWords(number);
            const auto lastSpace = base.find_last_of(' ');
            if (lastSpace == std::string::npos)
            {
                return base + "th";
            }

            const auto prefix = base.substr(0, lastSpace + 1);
            const auto lastWord = base.substr(lastSpace + 1);
            for (int64_t i = 0; i < 100; ++i)
            {
                if (numberToWords(i) == lastWord)
                {
                    return prefix + ordinalToWords(i);
                }
            }
            return base + "th";
        }

        std::string removeCommasFromNumbers(const std::string& text)
        {
            static const std::regex commaNumberRe("([0-9][0-9,]+[0-9])");
            std::string result;
            std::sregex_iterator current(text.begin(), text.end(), commaNumberRe);
            std::sregex_iterator end;
            size_t last = 0;
            for (; current != end; ++current)
            {
                const auto match = *current;
                result.append(text, last, static_cast<size_t>(match.position()) - last);
                auto number = match.str(1);
                number.erase(std::remove(number.begin(), number.end(), ','), number.end());
                result += number;
                last = static_cast<size_t>(match.position() + match.length());
            }
            result.append(text, last, std::string::npos);
            return result;
        }

        std::string expandDollarAmount(const std::smatch& match)
        {
            const auto amount = match.str(1);
            const auto dot = amount.find('.');
            if (dot != std::string::npos && amount.find('.', dot + 1) != std::string::npos)
            {
                return amount + " dollars";
            }

            const auto dollarsPart = dot == std::string::npos ? amount : amount.substr(0, dot);
            const auto centsPart = dot == std::string::npos ? std::string() : amount.substr(dot + 1);
            const auto dollars = dollarsPart.empty() ? 0 : std::stoll(dollarsPart);
            const auto cents = centsPart.empty() ? 0 : std::stoll(centsPart);

            std::vector<std::string> words;
            if (dollars != 0)
            {
                words.push_back(numberToWords(dollars));
                words.push_back(dollars == 1 ? "dollar" : "dollars");
            }
            if (cents != 0)
            {
                words.push_back(numberToWords(cents));
                words.push_back(cents == 1 ? "cent" : "cents");
            }
            if (words.empty())
            {
                return "zero dollars";
            }
            return joinWords(words);
        }

        std::string replaceRegex(
            const std::string& text,
            const std::regex& pattern,
            const std::function<std::string(const std::smatch&)>& replacement)
        {
            std::string result;
            std::sregex_iterator current(text.begin(), text.end(), pattern);
            std::sregex_iterator end;
            size_t last = 0;
            for (; current != end; ++current)
            {
                const auto match = *current;
                result.append(text, last, static_cast<size_t>(match.position()) - last);
                result += replacement(match);
                last = static_cast<size_t>(match.position() + match.length());
            }
            result.append(text, last, std::string::npos);
            return result;
        }

        struct Abbreviation
        {
            std::regex pattern;
            std::string replacement;
        };

