        std::vector<std::string> splitUtf8(const std::string& text)
        {
            std::vector<std::string> result;
            for (size_t i = 0; i < text.size();)
            {
                const auto byte = static_cast<unsigned char>(text[i]);
                size_t length = 1;
                if ((byte & 0xE0) == 0xC0)
                {
                    length = 2;
                }
                else if ((byte & 0xF0) == 0xE0)
                {
                    length = 3;
                }
                else if ((byte & 0xF8) == 0xF0)
                {
                    length = 4;
                }

                if (i + length > text.size())
                {
                    length = 1;
                }
                result.push_back(text.substr(i, length));
                i += length;
            }
            return result;
        }

        void appendUtf8Symbols(std::vector<std::string>& result, const std::string& text)
        {
            for (const auto& symbol : splitUtf8(text))
            {
                result.push_back(symbol);
            }
        }

        std::vector<std::string> buildSymbols()
        {
            std::vector<std::string> result;
            result.push_back("_");

            appendUtf8Symbols(
                result,
                ";:,.!?"
                "\xC2\xA1\xC2\xBF"
                "\xE2\x80\x94\xE2\x80\xA6"
                "\""
                "\xC2\xAB\xC2\xBB"
                "\xE2\x80\x9C\xE2\x80\x9D"
                " ");
            appendUtf8Symbols(
                result,
                "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz");

            // TODO: Python VITS appends a large IPA symbol table here. Add it
            // with generated byte escapes when the phonemizer path is wired in.
            return result;
        }

        std::string replaceAll(std::string text, const std::string& from, const std::string& to)
        {
            size_t pos = 0;
            while ((pos = text.find(from, pos)) != std::string::npos)
            {
                text.replace(pos, from.size(), to);
                pos += to.size();
            }
            return text;
        }

        std::string fallbackPhonemizeEnglish(const std::string& text)
        {
            // Python VITS calls phonemizer/espeak here. Keep this as a small
            // compatibility hook until an espeak-backed phonemizer is wired in.
            return text;
        }

